"""Process documentation exporters.

Confluence storage format is XHTML with Confluence's own macro elements. Pasting
the output into a page via the Confluence REST API (or the source editor)
produces a formatted page, not a wall of text — which is the point: the tool
should hand a governance team a publishable artefact, not homework.
"""

from __future__ import annotations

from xml.sax.saxutils import escape

from ..schema import ProcessSpec, TASK_KINDS


def _status_macro(text: str, colour: str) -> str:
    return (
        '<ac:structured-macro ac:name="status">'
        f'<ac:parameter ac:name="colour">{colour}</ac:parameter>'
        f'<ac:parameter ac:name="title">{escape(text)}</ac:parameter>'
        "</ac:structured-macro>"
    )


def _score_colour(score: int) -> str:
    if score >= 90:
        return "Green"
    if score >= 70:
        return "Yellow"
    return "Red"


def to_confluence_storage(spec: ProcessSpec, report: dict, bpmn_filename: str = "") -> str:
    out: list[str] = []
    a = out.append

    a('<ac:structured-macro ac:name="info"><ac:rich-text-body>')
    a(
        "<p>Generated by OpenProcess from "
        f"<strong>{escape(spec.source_document or 'an uploaded policy document')}</strong>. "
        "Review before publishing — this page is a draft for the process owner to confirm.</p>"
    )
    a("</ac:rich-text-body></ac:structured-macro>")

    a("<h2>Process header</h2>")
    a("<table><tbody>")
    rows = [
        ("Process", spec.name),
        ("Version", spec.version),
        ("Process owner", spec.owner or "— not stated in source —"),
        ("Purpose", spec.purpose or "— not stated in source —"),
        ("Scope", spec.scope or "— not stated in source —"),
        ("Trigger", spec.trigger or "— not stated in source —"),
        ("Framework classification",
         f"{spec.pcf_id} {spec.pcf_name}".strip() or "— unclassified —"),
        ("ITIL 4 practice", spec.itil_practice or "— unmapped —"),
    ]
    for label, value in rows:
        a(f"<tr><th>{escape(label)}</th><td>{escape(str(value))}</td></tr>")
    a(
        "<tr><th>Governance score</th><td>"
        + _status_macro(f"{report['score']} / 100 — {report['verdict']}",
                        _score_colour(report["score"]))
        + "</td></tr>"
    )
    a("</tbody></table>")

    if bpmn_filename:
        a("<h2>Process model</h2>")
        a(
            '<ac:structured-macro ac:name="view-file">'
            f'<ac:parameter ac:name="name"><ri:attachment ri:filename="{escape(bpmn_filename)}" /></ac:parameter>'
            "</ac:structured-macro>"
        )
        a(
            f"<p>The attached <code>{escape(bpmn_filename)}</code> is standards-compliant "
            "BPMN 2.0 and can be imported directly into the process management system.</p>"
        )

    a("<h2>Roles and responsibilities</h2>")
    a("<table><tbody><tr><th>Activity</th><th>Lane</th><th>Responsible</th>"
      "<th>Accountable</th><th>Consulted</th><th>Informed</th></tr>")
    for node in spec.nodes:
        if node.kind not in TASK_KINDS:
            continue
        lane = spec.lane(node.lane)
        a(
            "<tr>"
            f"<td>{escape(node.name)}</td>"
            f"<td>{escape(lane.name if lane else '')}</td>"
            f"<td>{escape(node.raci.responsible)}</td>"
            f"<td>{escape(node.raci.accountable)}</td>"
            f"<td>{escape(node.raci.consulted)}</td>"
            f"<td>{escape(node.raci.informed)}</td>"
            "</tr>"
        )
    a("</tbody></table>")

    controls = [n for n in spec.nodes if n.control.strip()]
    if controls:
        a("<h2>Control points</h2>")
        a("<table><tbody><tr><th>Activity</th><th>Control</th><th>System</th></tr>")
        for node in controls:
            a(
                f"<tr><td>{escape(node.name)}</td><td>{escape(node.control)}</td>"
                f"<td>{escape(node.system)}</td></tr>"
            )
        a("</tbody></table>")

    a("<h2>Open governance findings</h2>")
    open_findings = [f for f in report["findings"] if f["severity"] != "info"]
    if not open_findings:
        a("<p>No open findings. The model meets all modelling conventions.</p>")
    else:
        a("<table><tbody><tr><th>Severity</th><th>Rule</th><th>Finding</th>"
          "<th>Remediation</th></tr>")
        for finding in open_findings:
            colour = "Red" if finding["severity"] == "error" else "Yellow"
            a(
                "<tr><td>" + _status_macro(finding["severity"], colour) + "</td>"
                f"<td><code>{escape(finding['rule'])}</code></td>"
                f"<td>{escape(finding['message'])}</td>"
                f"<td>{escape(finding['remediation'])}</td></tr>"
            )
        a("</tbody></table>")

    return "\n".join(out) + "\n"


def to_markdown(spec: ProcessSpec, report: dict) -> str:
    out: list[str] = []
    a = out.append
    a(f"# {spec.name}")
    a("")
    a(f"**Version** {spec.version} · **Owner** {spec.owner or '_not stated_'} · "
      f"**Governance score** {report['score']}/100 ({report['verdict']})")
    a("")
    a(f"**Purpose.** {spec.purpose or '_not stated in source_'}")
    a("")
    a(f"**Scope.** {spec.scope or '_not stated in source_'}")
    a("")
    a(f"**Trigger.** {spec.trigger or '_not stated in source_'}")
    a("")
    a(f"**Classification.** {spec.pcf_id} {spec.pcf_name} · "
      f"ITIL 4: {spec.itil_practice or '_unmapped_'}")
    a("")
    a("## Roles and responsibilities")
    a("")
    a("| Activity | Lane | R | A | C | I |")
    a("| --- | --- | --- | --- | --- | --- |")
    for node in spec.nodes:
        if node.kind not in TASK_KINDS:
            continue
        lane = spec.lane(node.lane)
        a(f"| {node.name} | {lane.name if lane else ''} | {node.raci.responsible} | "
          f"{node.raci.accountable} | {node.raci.consulted} | {node.raci.informed} |")
    a("")
    a("## Governance findings")
    a("")
    open_findings = [f for f in report["findings"] if f["severity"] != "info"]
    if not open_findings:
        a("No open findings.")
    for finding in open_findings:
        target = f" — `{finding['element_name']}`" if finding["element_name"] else ""
        a(f"- **{finding['severity']}** `{finding['rule']}`{target}: "
          f"{finding['message']} _{finding['remediation']}_")
    a("")
    return "\n".join(out)
