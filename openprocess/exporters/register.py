"""Excel process register.

A governance team's real deliverable is not one diagram — it is a register they
can sort, filter and report on. This writes the register a BPM team would
actually keep: one row per process, one row per activity, one row per finding.
"""

from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from ..schema import ProcessSpec, TASK_KINDS

INK = "1A1D21"
PAPER = "F2F1ED"
RULE = "D8D6D0"
GOOD = "2E7D4F"
WARN = "B87A00"
BAD = "B03A2E"

HEADER_FILL = PatternFill("solid", fgColor=INK)
HEADER_FONT = Font(color="FFFFFF", bold=True, size=10, name="Calibri")
THIN = Side(style="thin", color=RULE)
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _header(ws, headers: list[str], widths: list[int]) -> None:
    for index, (title, width) in enumerate(zip(headers, widths), start=1):
        cell = ws.cell(row=1, column=index, value=title)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center")
        ws.column_dimensions[get_column_letter(index)].width = width
    ws.row_dimensions[1].height = 22
    ws.freeze_panes = "A2"


def _score_font(score: int) -> Font:
    colour = GOOD if score >= 90 else WARN if score >= 70 else BAD
    return Font(bold=True, color=colour, size=12)


def write_register(results: list[tuple[ProcessSpec, dict]], path: str | Path) -> Path:
    """results: list of (spec, governance report)."""
    path = Path(path)
    wb = Workbook()

    # ---- Dashboard ----
    ws = wb.active
    ws.title = "Dashboard"
    ws["A1"] = "IT process governance register"
    ws["A1"].font = Font(bold=True, size=16, color=INK)
    ws["A2"] = "Generated by OpenProcess"
    ws["A2"].font = Font(size=10, color="6B6A65")

    scores = [r["score"] for _, r in results] or [0]
    stats = [
        ("Processes in register", len(results)),
        ("Average governance score", round(sum(scores) / len(scores))),
        ("Ready to publish", sum(1 for _, r in results if r["score"] >= 90)),
        ("Open errors", sum(r["counts"]["errors"] for _, r in results)),
        ("Open warnings", sum(r["counts"]["warnings"] for _, r in results)),
    ]
    for offset, (label, value) in enumerate(stats):
        row = 4 + offset
        ws.cell(row=row, column=1, value=label).font = Font(size=11, color=INK)
        cell = ws.cell(row=row, column=2, value=value)
        cell.font = Font(bold=True, size=11)
    ws.column_dimensions["A"].width = 30
    ws.column_dimensions["B"].width = 14

    # ---- Register ----
    ws = wb.create_sheet("Register")
    _header(
        ws,
        ["Process", "Key", "Owner", "Framework ID", "Framework element",
         "ITIL 4 practice", "Activities", "Score", "Verdict", "Errors", "Warnings"],
        [34, 18, 24, 14, 34, 30, 11, 9, 26, 9, 11],
    )
    for row, (spec, report) in enumerate(results, start=2):
        activities = sum(1 for n in spec.nodes if n.kind in TASK_KINDS)
        values = [
            spec.name, spec.key, spec.owner, spec.pcf_id, spec.pcf_name,
            spec.itil_practice, activities, report["score"], report["verdict"],
            report["counts"]["errors"], report["counts"]["warnings"],
        ]
        for column, value in enumerate(values, start=1):
            cell = ws.cell(row=row, column=column, value=value)
            cell.border = BORDER
            if column == 8:
                cell.font = _score_font(report["score"])
                cell.alignment = Alignment(horizontal="center")
    ws.auto_filter.ref = f"A1:K{max(2, len(results) + 1)}"

    # ---- RACI ----
    ws = wb.create_sheet("RACI")
    _header(
        ws,
        ["Process", "Lane", "Activity", "Responsible", "Accountable",
         "Consulted", "Informed", "Control point", "System"],
        [28, 22, 34, 22, 22, 22, 22, 26, 22],
    )
    row = 2
    for spec, _ in results:
        for node in spec.nodes:
            if node.kind not in TASK_KINDS:
                continue
            lane = spec.lane(node.lane)
            values = [
                spec.name, lane.name if lane else "", node.name,
                node.raci.responsible, node.raci.accountable,
                node.raci.consulted, node.raci.informed, node.control, node.system,
            ]
            for column, value in enumerate(values, start=1):
                cell = ws.cell(row=row, column=column, value=value)
                cell.border = BORDER
                if column in (4, 5) and not value:
                    cell.fill = PatternFill("solid", fgColor="FBE9E7")
            row += 1
    ws.auto_filter.ref = f"A1:I{max(2, row - 1)}"

    # ---- Findings ----
    ws = wb.create_sheet("Findings")
    _header(
        ws,
        ["Process", "Severity", "Tier", "Rule", "Element", "Finding", "Remediation"],
        [28, 11, 14, 26, 26, 56, 56],
    )
    row = 2
    for spec, report in results:
        for finding in report["findings"]:
            values = [
                spec.name, finding["severity"], finding["tier"], finding["rule"],
                finding["element_name"], finding["message"], finding["remediation"],
            ]
            for column, value in enumerate(values, start=1):
                cell = ws.cell(row=row, column=column, value=value)
                cell.border = BORDER
                cell.alignment = Alignment(vertical="top", wrap_text=column in (6, 7))
                if column == 2:
                    colour = {"error": BAD, "warning": WARN}.get(finding["severity"], "6B6A65")
                    cell.font = Font(bold=True, color=colour)
            row += 1
    ws.auto_filter.ref = f"A1:G{max(2, row - 1)}"

    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path
